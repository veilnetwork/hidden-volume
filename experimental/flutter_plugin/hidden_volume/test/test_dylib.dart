// Shared dylib resolver for the plugin's Dart tests and for `bench/`.
//
// The previous per-test resolvers only searched for `hidden_volume_ffi.dll`
// (Windows extension), which made `flutter test` fail in `setUpAll`
// on macOS (`.dylib`) and Linux (`.so`). This helper picks the right
// extension for the running platform — and tries every probable
// search root — so the tests work uniformly across host OS.
//
// Naming convention: no `_test.dart` suffix so Dart's test runner
// does not auto-discover this as a test file.

import 'dart:ffi' show DynamicLibrary;
import 'dart:io';

/// Cargo build profiles to search, most-preferred first.
///
/// **`release` leads, and the order is load-bearing.** The UniFFI per-method
/// checksum table in `lib/src/bindings.dart` is generated by
/// `scripts/regen-dart-checksums.py` from whichever cdylib that script
/// resolves, and its documented build step is
/// `cargo build -p hidden-volume-ffi --release`. Release is also what
/// `scripts/release.sh` stages and what CI ships.
///
/// This file used to search `debug` first. That split the guarantee in half:
/// with both profiles built and only one refreshed,
/// `regen-dart-checksums.py --check` reported the table sound against
/// `target/release` while `flutter test` loaded `target/debug` and failed on
/// the very checksums the script had just certified. An integrity check that
/// passes on a library nobody executes is the "verified artifact is not the
/// executed artifact" split that audit HV-05 exists to close, reopened one
/// directory over.
///
/// `scripts/dylib_path.py` carries the same list for the Python side, and
/// `regen-dart-checksums.py` refuses to run when the two disagree — so this
/// constant cannot drift on its own.
const dylibProfileOrder = <String>['release', 'debug'];

/// Host-native `(prefix, stem, extension)` for the `cdylib`. macOS uses
/// `.dylib`, Linux `.so`, Windows `.dll`; `cdylib` outputs land in
/// `target/<profile>/` under the platform-default prefix and extension.
List<List<String>> _hostTriplets() {
  final triplets = <List<String>>[
    if (Platform.isMacOS) ['lib', 'hidden_volume_ffi', '.dylib'],
    if (Platform.isLinux) ['lib', 'hidden_volume_ffi', '.so'],
    if (Platform.isWindows) ['', 'hidden_volume_ffi', '.dll'],
  ];
  if (triplets.isEmpty) {
    throw StateError('unsupported host OS: ${Platform.operatingSystem}');
  }
  return triplets;
}

/// Every path [`resolveDylibPath`] will try, in the order it tries them.
///
/// Exposed so a test can assert the search honours [dylibProfileOrder]
/// rather than merely declaring it — see `test/checksum_test.dart`.
List<String> dylibCandidates() {
  final root = Directory.current.path;
  final searchRoots = <String>[
    // `flutter test` invoked from the plugin dir
    // (`experimental/flutter_plugin/hidden_volume/`) — ascend three
    // levels to find the workspace `target/`.
    '$root/../../../target',
    // `flutter test` invoked from the repo root.
    '$root/target',
  ];
  final candidates = <String>[];
  // Profile-major: a `release` build anywhere outranks a `debug` build
  // anywhere, so the preference expressed by `dylibProfileOrder` holds no
  // matter which working directory the runner was started from.
  for (final profile in dylibProfileOrder) {
    for (final base in searchRoots) {
      for (final triple in _hostTriplets()) {
        candidates.add('$base/$profile/${triple[0]}${triple[1]}${triple[2]}');
      }
    }
  }
  return candidates;
}

/// Find the built `hidden-volume-ffi` cdylib for the current host platform.
///
/// Prefers the profile the checksum table was generated from — see
/// [dylibProfileOrder]. Searches both "test runs from plugin dir" and "test
/// runs from repo root" layouts. Throws [StateError] with the full candidate
/// list if no file is found.
String resolveDylibPath() {
  final candidates = dylibCandidates();
  for (final p in candidates) {
    if (File(p).existsSync()) return p;
  }
  throw StateError('cdylib not found, searched: ${candidates.join(", ")}');
}

/// Convenience wrapper: resolve, open, return the [DynamicLibrary].
///
/// **This reaches the CALLING isolate only.** Every test here that spawns a
/// worker — `worker_death_test`, and anything else going through
/// `HvAsyncSpace._spawn` — runs its FFI in a fresh isolate that inherits no
/// Dart memory, so the library this opened is invisible there. The worker
/// re-runs the resolver in `lib/src/bindings.dart`, which falls back to the
/// bare `libhidden_volume_ffi.so` / `.dylib` and finds it only if the loader
/// already can.
///
/// On macOS it can, so those tests pass and the requirement stays invisible.
/// On Linux it cannot, and they fail with a raw `Failed to load dynamic
/// library` from inside the worker rather than anything that names the cause.
/// Measured on aarch64 Linux: 107 of 109 passed, and the two that did not were
/// this and nothing else.
///
/// The plugin already has the answer, and it is process-wide rather than
/// per-isolate — `bindings.dart` reads `XVEIL_HV_DYLIB` before anything else:
///
/// ```sh
/// cargo build -p hidden-volume-ffi --release
/// XVEIL_HV_DYLIB=$PWD/../../../target/release/libhidden_volume_ffi.so \
///   flutter test          # or set LD_LIBRARY_PATH to that directory
/// ```
///
/// With it set the whole suite is green on Linux. Nothing else in this
/// repository mentions that variable — it appears exactly once, where it is
/// read — which is why this note is here rather than in a wiki nobody opens.
DynamicLibrary openTestDylib() => DynamicLibrary.open(resolveDylibPath());
